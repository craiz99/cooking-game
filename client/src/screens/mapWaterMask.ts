/**
 * Returns true if the normalized US map coordinate (nx in [0..1], ny in [0..1])
 * sits over open water (oceans, Gulf, or Great Lakes) so the Purple Van deploys its inflatable raft.
 */
export function isMapWater(nx: number, ny: number): boolean {
  if (nx < 0 || nx > 1 || ny < 0 || ny > 1) return false;
  const col = Math.max(0, Math.min(WATER_MASK_COLS - 1, Math.floor(nx * WATER_MASK_COLS)));
  const row = Math.max(0, Math.min(WATER_MASK_ROWS - 1, Math.floor(ny * WATER_MASK_ROWS)));
  return WATER_MASK_GRID[row]?.[col] === "1";
}
